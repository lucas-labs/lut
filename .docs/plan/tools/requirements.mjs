#!/usr/bin/env node
// Builds .docs/product/requirements.md: every TER/PRO/PRJ/UX/AGT requirement of the proposal (taken from
// inventory/proposal-items.json) with its priority and the plan issues that cover it. The Implementation and Tests
// columns are written by hand; regenerating keeps them.
//
// usage: node .docs/plan/tools/requirements.mjs           write requirements.md
//        node .docs/plan/tools/requirements.mjs --check   exit 1 if requirements.md is missing ids or out of date
// validate.mjs runs the same check.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { INVENTORY_DIR, PLAN_DIR, REPO_ROOT, parsePlan, readJson } from "./lib.mjs";

export const REQUIREMENTS_PATH = join(REPO_ROOT, ".docs", "product", "requirements.md");

const GROUPS = [
  ["TER", "Terminal, sessions and navigation", "3.1"],
  ["PRO", "Profiles", "3.2"],
  ["PRJ", "Projects and persistent workspaces", "3.3"],
  ["UX", "Interface and customisation", "3.4"],
  ["AGT", "CLI agent integration", "3.5"],
];
const HEADER = ["ID", "Priority", "Requirement", "Issues", "Implementation", "Tests"];

/** Requirement rows from the proposal inventory and the plan's covers / Not planned entries. */
function requirementRows(planText) {
  const proposal = readJson(join(INVENTORY_DIR, "proposal-items.json"));
  const plan = parsePlan(planText);
  const covering = new Map(); // requirement id -> [issue ids]
  for (const epic of plan.epics)
    for (const issue of epic.issues)
      for (const id of issue.meta?.covers ?? []) covering.set(id, [...(covering.get(id) ?? []), issue.meta.id]);
  const notPlanned = new Map(plan.notPlanned.map((np) => [np.id, np.reason]));
  return proposal.items
    .filter((item) => item.kind === "requirement")
    .map((item) => {
      const m = item.text.match(/^(P\d)\s+(.*)$/);
      const issues = covering.get(item.id);
      return {
        id: item.id,
        priority: m?.[1] ?? "",
        text: m?.[2] ?? item.text,
        issues: issues ? issues.join(", ") : notPlanned.has(item.id) ? `Not planned: ${notPlanned.get(item.id)}` : "",
      };
    });
}

const splitRow = (line) =>
  line
    .trim()
    .replace(/^\||\|$/g, "")
    .split(/(?<!\\)\|/)
    .map((cell) => cell.trim());

/** The hand-written Implementation and Tests cells of an existing requirements.md, by id. */
function manualCells(text) {
  const cells = new Map();
  for (const line of text.split(/\r?\n/)) {
    if (!line.startsWith("|")) continue;
    const row = splitRow(line);
    if (row.length !== HEADER.length || !/^[A-Z]+-\d{3}$/.test(row[0])) continue;
    cells.set(row[0], { implementation: row[4], tests: row[5] });
  }
  return cells;
}

const escapeCell = (s) => s.replace(/\|/g, "\\|");
// Prettier-compatible aligned table (every cell padded to its column width, at least 3).
function table(rows) {
  const widths = HEADER.map((_, c) => Math.max(3, ...[HEADER, ...rows].map((r) => [...r[c]].length)));
  const line = (r) => `| ${r.map((cell, c) => cell.padEnd(widths[c] + cell.length - [...cell].length)).join(" | ")} |`;
  return [line(HEADER), `| ${widths.map((w) => "-".repeat(w)).join(" | ")} |`, ...rows.map(line)].join("\n");
}

export function buildRequirements(planText, existingText = "") {
  const manual = manualCells(existingText);
  const rows = requirementRows(planText);
  const out = [
    "# Requirements traceability",
    "",
    "<!-- Generated by `node .docs/plan/tools/requirements.mjs`. Only the Implementation and Tests columns are edited",
    "by hand; regenerating keeps them. -->",
    "",
    "Every product requirement of [`.docs/proposal.md`](../proposal.md) §3, the plan issues that implement it and, once",
    "done, where it lives and which tests verify it. Ids, priorities and requirement texts come from the proposal (in",
    "Spanish, as written there); the Issues column comes from the `covers` lists of",
    "[`.docs/plan/plan.md`](../plan/plan.md). Priorities: **P0** first use, **P1** extended MVP, **P2** later.",
    "",
    "The PR that completes a requirement fills in its Implementation (paths or modules) and Tests (test files or the",
    "manual check). `node .docs/plan/tools/validate.mjs` fails when this file misses a requirement or its generated",
    "columns are out of date.",
  ];
  for (const [prefix, title, section] of GROUPS) {
    const group = rows.filter((r) => r.id.startsWith(`${prefix}-`));
    out.push("", `## ${title} (${prefix}, §${section})`, "");
    out.push(
      table(
        group.map((r) => {
          const m = manual.get(r.id) ?? { implementation: "", tests: "" };
          return [r.id, r.priority, escapeCell(r.text), escapeCell(r.issues), m.implementation, m.tests];
        }),
      ),
    );
  }
  const known = new Set(GROUPS.map(([p]) => p));
  const stray = rows.filter((r) => !known.has(r.id.split("-")[0]));
  return { text: `${out.join("\n")}\n`, ids: rows.map((r) => r.id), stray };
}

/** Errors for validate.mjs: requirements.md missing, missing ids, unknown ids or stale generated columns. */
export function requirementsErrors(planText) {
  if (!existsSync(REQUIREMENTS_PATH)) return [".docs/product/requirements.md is missing: run node .docs/plan/tools/requirements.mjs"];
  const current = readFileSync(REQUIREMENTS_PATH, "utf8").replace(/\r\n/g, "\n");
  const { text, ids, stray } = buildRequirements(planText, current);
  const errors = stray.map((r) => `requirements: ${r.id} has a prefix requirements.mjs does not know`);
  const listed = new Set(manualCells(current).keys());
  for (const id of ids) if (!listed.has(id)) errors.push(`requirements: ${id} is missing from .docs/product/requirements.md`);
  for (const id of listed) if (!ids.includes(id)) errors.push(`requirements: ${id} is not a requirement of the proposal`);
  if (!errors.length && text !== current) errors.push("requirements: .docs/product/requirements.md is out of date: run node .docs/plan/tools/requirements.mjs");
  return errors;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const planText = readFileSync(join(PLAN_DIR, "plan.md"), "utf8");
  if (process.argv.includes("--check")) {
    const errors = requirementsErrors(planText);
    for (const e of errors) console.error(`error: ${e}`);
    console.log(errors.length ? "requirements: FAILED" : "requirements: OK");
    process.exit(errors.length ? 1 : 0);
  }
  const existing = existsSync(REQUIREMENTS_PATH) ? readFileSync(REQUIREMENTS_PATH, "utf8") : "";
  const { text, ids, stray } = buildRequirements(planText, existing);
  if (stray.length) {
    console.error(`error: unknown requirement prefixes: ${stray.map((r) => r.id).join(", ")}`);
    process.exit(1);
  }
  writeFileSync(REQUIREMENTS_PATH, text);
  console.log(`wrote ${ids.length} requirements to .docs/product/requirements.md`);
}
